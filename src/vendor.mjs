// Check if MAC is locally administered / randomized (common on iOS/Android private Wi-Fi)
export function isLocallyAdministeredMac(mac) {
  if (!mac || mac.length < 2) return false;
  const firstByte = parseInt(mac.slice(0, 2), 16);
  // If bit 1 (0x02) is set, it is locally administered / randomized
  return (firstByte & 0x02) !== 0;
}

export function resolveVendor(mac) {
  if (!mac) return 'Desconocido';
  const clean = mac.toLowerCase();
  const prefix = clean.split(':').slice(0, 3).map((p) => p.padStart(2, '0')).join(':');

  if (OUI_MAP[prefix]) {
    return OUI_MAP[prefix];
  }

  if (isLocallyAdministeredMac(clean)) {
    return 'Dispositivo Privado (MAC Aleatoria - iOS/Android)';
  }

  return 'Dispositivo de Red';
}
